<section class="section">
  <div class="container narrow">
    <h2 style="text-align: center; margin-bottom: 32px;">Roof cost breakdown by repair type</h2>
    
    <div class="card" style="margin-bottom: 24px;">
      <h3>Leak repair & patching</h3>
      <p><strong>Average cost:</strong> $300–$900</p>
      <p class="muted">Simple leak repairs around chimneys or vents cost $300-$500. More extensive repairs requiring multiple shingles or flashing work run $600-$1,200.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Itemized labor hours, materials list (shingles, tar, flashing), photos of damage, and warranty on repair work (typically 1-2 years).</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Shingle replacement (partial)</h3>
      <p><strong>Average cost:</strong> $400–$1,200</p>
      <p class="muted">Replacing damaged shingles in a small area (50-100 sq ft) costs $400-$800. Larger sections or areas requiring decking repair cost more.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Square footage clearly stated, shingle brand and color match to existing roof, labor per square foot reasonable for your market.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Flashing repair or replacement</h3>
      <p><strong>Average cost:</strong> $200–$600</p>
      <p class="muted">Chimney or vent flashing repairs cost $200-$400. Valley flashing replacement runs $400-$800 due to more extensive work removing and reinstalling shingles.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Type of flashing specified (aluminum vs. copper), linear feet being replaced, and whether waterproofing sealant is included.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Full roof replacement (asphalt shingles)</h3>
      <p><strong>Average cost:</strong> $5,000–$10,000</p>
      <p class="muted">For average 1,500-2,000 sq ft home. Price includes tear-off, disposal, new underlayment, drip edge, and installation. Architectural shingles cost 15-25% more than 3-tab.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Total squares (100 sq ft), shingle brand and warranty (20-30 years), underlayment type (felt vs. synthetic), and disposal fees itemized.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Metal or tile roof installation</h3>
      <p><strong>Average cost:</strong> $10,000–$25,000+</p>
      <p class="muted">Metal roofs cost $10-$16 per sq ft installed. Tile roofs run $15-$25+ per sq ft. Both last 40-70 years vs. 20-30 for asphalt, justifying higher upfront costs.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Material gauge or thickness, finish type (painted vs. natural), warranty length (30-50 years typical), and structural reinforcement if needed.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Roof inspection</h3>
      <p><strong>Average cost:</strong> $100–$300</p>
      <p class="muted">Professional roof inspections identify issues before they become expensive. Required for home sales, insurance claims, and recommended every 2-3 years.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Written report with photos, life expectancy estimate, maintenance recommendations, and whether cost is credited toward repairs.</p>
    </div>
  </div>
</section>

