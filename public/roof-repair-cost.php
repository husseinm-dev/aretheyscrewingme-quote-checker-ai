    <div class="card" style="margin-bottom: 20px;">
      <h3>How long should a roof replacement take?</h3>
      <p class="muted">Most residential roofs (1,500-2,000 sq ft) take 1-3 days. Metal or tile roofs take longer (3-5 days). Delays beyond this may indicate crew size or weather issues.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I repair or replace my roof?</h3>
      <p class="muted">If your roof is 15+ years old with widespread damage, replacement is often smarter. For roofs under 10 years with localized issues, repairs make sense.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What's included in roof replacement pricing?</h3>
      <p class="muted">Should include tear-off, disposal, underlayment, drip edge, valley metal, ridge vents, new shingles, and cleanup. Permits and dump fees are sometimes extra—ask upfront.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Do I need to be home during roof work?</h3>
      <p class="muted">Not necessarily, but being available for questions helps. Expect noise and vibration—warn neighbors, secure outdoor items, and cover attic items to prevent dust infiltration.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What warranty should I expect?</h3>
      <p class="muted">Shingles come with manufacturer warranties (20-50 years). Contractor workmanship warranties typically run 1-10 years. Get both in writing before work starts.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How do I verify contractor credentials?</h3>
      <p class="muted">Check license, insurance, and bonding. Request references and check reviews. Verify they pull permits—unlicensed work can void insurance and create liability issues.</p>
