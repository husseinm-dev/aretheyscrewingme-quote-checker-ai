      </div>
      <div class="card">
        <h3>Time repairs strategically</h3>
        <p class="muted">Schedule in fall or early spring when demand is lower. Avoid summer peak season when contractors charge premium rates.</p>
      </div>
      <div class="card">
        <h3>Bundle with neighbors</h3>
        <p class="muted">If multiple homes in your neighborhood need roofing, contractors may offer 5-10% discounts for bulk scheduling (saves mobilization costs).</p>
      </div>
      <div class="card">
        <h3>Check insurance coverage first</h3>
        <p class="muted">Storm damage, hail, or wind damage may be covered. Get professional assessment before filing claims—insurers sometimes pay most or all replacement costs.</p>
      </div>
      <div class="card">
        <h3>Verify warranty transferability</h3>
        <p class="muted">If selling within warranty period, choose shingles with transferable warranties—adds value and marketability to your home.</p>
