<section class="section">
  <div class="container narrow">
    <h2 style="text-align: center; margin-bottom: 32px;">HVAC cost breakdown by repair type</h2>
    
    <div class="card" style="margin-bottom: 24px;">
      <h3>AC refrigerant recharge</h3>
      <p><strong>Average cost:</strong> $150–$400</p>
      <p class="muted">Most recharges need 1-3 pounds of refrigerant at $50-$150/lb depending on type (R-410A vs. R-22). If your system needs frequent recharges, you likely have a leak that needs repair first.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Clear statement of pounds added, refrigerant type, and pressure test results before/after.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Thermostat replacement</h3>
      <p><strong>Average cost:</strong> $150–$350</p>
      <p class="muted">Basic programmable thermostats cost $70-$150 installed, while smart thermostats (Nest, Ecobee) run $200-$400 with installation. Wi-Fi setup may add $50.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Separate unit and labor costs, compatibility verified before purchase, and included programming/setup.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>AC capacitor or contactor replacement</h3>
      <p><strong>Average cost:</strong> $150–$450</p>
      <p class="muted">Capacitors are $10-$40 parts but require proper sizing and installation—labor adds the bulk of cost. Contactors similarly cost $20-$100 in parts with labor making up the rest.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Diagnosis explaining why part failed, part specifications (µF rating for capacitors), and warranty on parts/labor.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>AC compressor repair or replacement</h3>
      <p><strong>Average cost:</strong> $600–$2,000</p>
      <p class="muted">Compressor replacement is one of the most expensive AC repairs since it's the heart of the system. For older units (12+ years), full system replacement may be more cost-effective.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Discussion of repair vs. replace economics, compressor warranty (usually 5-10 years), and refrigerant recovery/recharge included in price.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Furnace igniter or flame sensor replacement</h3>
      <p><strong>Average cost:</strong> $150–$400</p>
      <p class="muted">Hot surface igniters and flame sensors are common furnace failures. Parts cost $20-$100, with the rest being labor to access and install.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Explanation of failure (cracked igniter, dirty sensor), OEM vs. aftermarket part pricing, and service call fee structure.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Duct work repair or sealing</h3>
      <p><strong>Average cost:</strong> $300–$1,200</p>
      <p class="muted">Duct sealing with mastic costs $300-$600 for average homes. Major duct repairs or replacements cost $700-$2,000 depending on access and extent of damage.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Linear feet affected, material costs (mastic, metal, insulation), and energy savings estimates post-repair.</p>
    </div>
  </div>
</section>

