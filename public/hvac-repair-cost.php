    <h2 style="text-align: center; margin-bottom: 32px;">Common HVAC pricing questions</h2>
    
    <div class="card" style="margin-bottom: 20px;">
      <h3>Why do HVAC companies charge diagnostic fees?</h3>
      <p class="muted">Diagnostic fees ($75-$150) cover the technician's time, equipment, and expertise to identify the problem. Many credit this toward the repair if you proceed.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I repair or replace my HVAC system?</h3>
      <p class="muted">Use the $5,000 rule: multiply repair cost by system age. If it exceeds $5,000 and your system is 10+ years old, replacement is usually smarter.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What's a reasonable price for refrigerant?</h3>
      <p class="muted">R-410A costs $50-$100/lb installed. R-22 (phased out) now costs $80-$150/lb. Be wary of quotes that don't specify pounds added.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Do I need to replace both the AC and furnace together?</h3>
      <p class="muted">Not always—but if one is failing and the other is 12+ years old, replacing both together saves on labor and ensures system compatibility.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What SEER rating should I get for a new system?</h3>
      <p class="muted">Minimum is 14 SEER (federal standard). 16-18 SEER offers good efficiency without premium pricing. 20+ SEER rarely pays back in savings unless you live in extreme climates.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Can I finance HVAC repairs or replacement?</h3>
      <p class="muted">Most HVAC companies offer financing—0% for 12-24 months is common for replacements. Read terms carefully as deferred interest can be expensive.</p>
    </div>
  </div>
</section>

