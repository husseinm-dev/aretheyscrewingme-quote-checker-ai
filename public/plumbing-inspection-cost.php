    <h2 style="text-align: center; margin-bottom: 32px;">Plumbing inspection cost breakdown by service type</h2>
    
    <div class="card" style="margin-bottom: 24px;">
      <h3>Basic plumbing inspection</h3>
      <p><strong>Average cost:</strong> $100–$250</p>
      <p class="muted">Visual inspection of exposed pipes, fixtures, water heater, and shutoff valves. Takes 1-2 hours. Identifies visible leaks, corrosion, improper installations, and code violations.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Hourly rate or flat fee clearly stated, inspection checklist provided, written report included, and whether photos are part of standard service.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Pre-purchase home plumbing inspection</h3>
      <p><strong>Average cost:</strong> $150–$400</p>
      <p class="muted">Comprehensive inspection for home buyers. Includes all visible plumbing, water pressure tests, drain function tests, and water heater assessment. Critical for older homes.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Detailed written report with repair cost estimates, photos of issues, coverage of all fixtures and systems, and recommendations prioritized by urgency.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Camera drain/sewer inspection</h3>
      <p><strong>Average cost:</strong> $200–$800</p>
      <p class="muted">Specialized camera fed through drains to inspect pipe interiors. Identifies blockages, cracks, root intrusion, or collapsed pipes. Essential before major drain repairs or property purchases.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Video recording provided, linear feet inspected clearly stated, marker flags placed where issues found, and whether locating service is included.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Leak detection service</h3>
      <p><strong>Average cost:</strong> $150–$400</p>
      <p class="muted">Uses listening devices, moisture meters, or thermal imaging to find hidden leaks in walls, floors, or underground. Saves thousands by pinpointing exact leak location.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Technology used specified (acoustic, thermal), time estimate provided, leak location marked, and whether service fee is credited toward repair if you hire them.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Water pressure & flow test</h3>
      <p><strong>Average cost:</strong> $100–$200</p>
      <p class="muted">Tests static and dynamic water pressure at multiple fixtures. Identifies low pressure issues, pipe restrictions, or oversized water heater problems affecting performance.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Pressure readings documented at multiple locations, flow rate measured in GPM, recommendations for pressure regulators or booster pumps if needed.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Backflow testing & certification</h3>
      <p><strong>Average cost:</strong> $75–$150</p>
      <p class="muted">Required annually by many municipalities for properties with irrigation systems or commercial connections. Tests backflow prevention devices to ensure drinking water safety.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Certification filed with city/county, test report provided to homeowner, device repairs quoted separately, and notice of next required test date.</p>
    </div>
  </div>
</section>

