      <p><strong>Average cost:</strong> $150–$600 per axle</p>
      <p class="muted">Pads alone cost $150-$350. Pads + rotors run $300-$600. Caliper replacement adds $150-$300 per side. Brake fluid flush costs $70-$120.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Labor time (1-2 hours per axle), parts brand (Brembo, Wagner, Raybestos), and whether hardware/anti-rattle clips are included.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Battery, starter, and alternator</h3>
      <p><strong>Average cost:</strong> $100–$800</p>
      <p class="muted">Battery replacement costs $100-$250. Starters run $300-$600. Alternators cost $400-$800. Group 24-27 batteries are standard; larger or AGM batteries cost more.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Battery CCA rating, starter/alternator part numbers, core charge refunds, and warranty length (typically 1-3 years).</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Transmission service</h3>
      <p><strong>Average cost:</strong> $150–$3,500+</p>
      <p class="muted">Fluid change costs $150-$250. Filter replacement runs $200-$400. Transmission rebuild costs $1,800-$3,500. Replacement with used/rebuilt unit: $1,500-$3,000.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Quarts of fluid, filter brand, pan gasket replacement, and whether diagnostic scan confirmed internal damage vs. simple service needs.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Suspension & steering</h3>
      <p><strong>Average cost:</strong> $300–$1,200</p>
      <p class="muted">Strut/shock replacement costs $400-$900 per pair. Control arm replacement runs $300-$600 per side. Alignment costs $75-$150. Ball joints cost $200-$500 per side.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Part brand (Monroe, KYB, Moog), whether alignment is included, labor time, and whether bushings/mounts are separate line items.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
