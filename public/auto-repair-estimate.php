    <h2 style="text-align: center; margin-bottom: 32px;">Common auto repair estimate questions</h2>
    
    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I go to the dealership or independent shop?</h3>
      <p class="muted">Dealerships charge 20-40% more but use OEM parts and specialized tools. Independent shops offer better value for out-of-warranty vehicles. ASE-certified techs ensure quality work.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How do I verify the diagnosis is correct?</h3>
      <p class="muted">Ask to see failed parts or diagnostic scan results. Get a second opinion for expensive repairs. Reputable shops gladly explain findings and show evidence of necessary work.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What warranty should I expect?</h3>
      <p class="muted">Parts typically carry 1-3 year warranties. Labor warranties run 30-90 days. Nationwide chains often offer longer coverage. Get warranty terms in writing before approving work.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Can I bring my own parts?</h3>
      <p class="muted">Some shops allow customer-supplied parts but won't warranty them. Others refuse due to liability concerns. Ask upfront—shops may match or beat online pricing to keep the business.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>When is repair not worth it?</h3>
      <p class="muted">If repair costs exceed 50% of vehicle value or if multiple expensive repairs loom (transmission + engine), replacement is often smarter. Consider age, mileage, and overall condition.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How do I avoid upselling?</h3>
      <p class="muted">Request written estimates before approving extra work. Decline services not in your owner's manual or due within 6 months. Ask "what happens if I wait?" for recommended services.</p>
    </div>
  </div>
</section>

