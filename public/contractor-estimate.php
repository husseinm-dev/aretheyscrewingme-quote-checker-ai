    <div class="card" style="margin-bottom: 24px;">
      <h3>Kitchen remodel</h3>
      <p><strong>Average cost:</strong> $12,000–$35,000</p>
      <p class="muted">Cabinet refacing and countertops start at $12,000. Full remodel with new cabinets, appliances, and layout changes costs $25,000-$50,000+.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Cabinet brand and linear feet, countertop material and square footage, appliance allowances, and electrical/plumbing scope clearly defined.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Deck construction</h3>
      <p><strong>Average cost:</strong> $4,000–$12,000</p>
      <p class="muted">Pressure-treated wood decks cost $15-$30 per sq ft. Composite decks run $30-$45 per sq ft. Railings, stairs, and built-in seating add $1,000-$5,000.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Square footage, material type (cedar vs. composite), post/beam specs, footing depth, and whether permit fees are included.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Basement finishing</h3>
      <p><strong>Average cost:</strong> $10,000–$30,000</p>
