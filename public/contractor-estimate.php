<section class="section">
  <div class="container narrow">
    <h2 style="text-align: center; margin-bottom: 32px;">Common contractor estimate questions</h2>
    
    <div class="card" style="margin-bottom: 20px;">
      <h3>How detailed should a contractor estimate be?</h3>
      <p class="muted">Should include materials (with brands/specs), labor hours or costs per trade, permits/fees, timeline, payment schedule, and warranty details. Avoid vague lump sums.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What's a reasonable deposit amount?</h3>
      <p class="muted">10-15% to secure your spot on the schedule. Anything over 25% upfront is a red flag. Never pay 50%+ before work starts—that's a common scam pattern.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I always choose the lowest bid?</h3>
      <p class="muted">Not necessarily. Lowest bids may use cheaper materials, cut corners, or underestimate scope (leading to change orders later). Compare middle-range quotes for best value.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How do I verify a contractor's credentials?</h3>
      <p class="muted">Check license status with your state licensing board. Verify insurance (general liability + workers comp). Ask for references and check online reviews across multiple platforms.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What happens if the project goes over budget?</h3>
      <p class="muted">Written contracts should define how change orders work. Get pricing in writing before approving extras. Legitimate overruns (hidden damage) are normal; vague "unexpected costs" are not.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How long should a typical remodel take?</h3>
      <p class="muted">Bathroom: 2-4 weeks. Kitchen: 4-8 weeks. Basement: 4-8 weeks. Home addition: 3-6 months. Factor in permit delays, inspections, and material delivery times.</p>
    </div>
