      </div>
      <div class="card card-outline">
        <h3>Complexity & access</h3>
        <p class="muted">Hard-to-reach repairs (behind walls, under equipment) take longer and cost more. Removing surrounding components to access broken parts adds labor time.</p>
      </div>
      <div class="card card-outline">
        <h3>Warranty coverage</h3>
        <p class="muted">In-warranty repairs should be free or discounted. Extended warranties may cover parts but not labor. Always verify coverage before approving paid repairs.</p>
      </div>
      <div class="card card-outline">
        <h3>Age & condition</h3>
        <p class="muted">Older systems may require multiple repairs or hard-to-find parts. If repair costs exceed 50% of replacement value, replacement is often smarter financially.</p>
