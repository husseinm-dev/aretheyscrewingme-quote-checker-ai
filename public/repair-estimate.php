      <h3>Auto repair</h3>
      <p><strong>Average cost:</strong> $150–$1,200</p>
      <p class="muted">Brake pads cost $150-$300. Suspension work runs $300-$800. Major repairs (transmission, engine) cost $1,000-$4,000+. Dealerships charge 20-40% more than independent shops.</p>
      <p class="muted"><strong>Fair price indicators:</strong> OEM vs. aftermarket parts specified, labor hours by task, shop rate disclosed upfront, and whether warranty is provided on work.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Plumbing repair</h3>
      <p><strong>Average cost:</strong> $150–$850</p>
