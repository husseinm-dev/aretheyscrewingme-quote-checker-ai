    <h2 style="text-align: center; margin-bottom: 32px;">Common repair estimate questions</h2>
    
    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I authorize repairs before getting a quote?</h3>
      <p class="muted">Never. Reputable techs diagnose first and provide written quotes before starting work. Verbal estimates or "we'll see what it needs" approaches lead to surprise bills.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>When should I repair vs. replace?</h3>
      <p class="muted">If the item is 75%+ through its expected lifespan and repair costs exceed 50% of replacement cost, replacement is usually smarter. Consider energy savings and warranties too.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How do I verify fair pricing?</h3>
      <p class="muted">Cross-reference part numbers on Amazon or auto parts sites. Check Angi, HomeAdvisor, or RepairPal for typical labor rates in your area. Compare to 2-3 other quotes.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What if I already approved expensive work?</h3>
      <p class="muted">If work hasn't started, you can cancel (may lose diagnostic fee). If completed and you believe you were overcharged, document everything and file complaints with BBB, state licensing boards, or small claims court.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Are flat-rate pricing guides fair?</h3>
      <p class="muted">Flat rates protect you from being charged for slow work but may cost more than hourly for quick jobs. Ask to see the rate book and compare total to hourly estimates.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What warranty should I expect?</h3>
      <p class="muted">Most repair work carries 30-90 day labor warranties. Parts typically have manufacturer warranties (90 days to lifetime). Get all warranty terms in writing before work starts.</p>
    </div>
  </div>
