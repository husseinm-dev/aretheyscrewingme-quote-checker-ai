<section class="section">
  <div class="container narrow">
    <h2 style="text-align: center; margin-bottom: 32px;">Common plumber pricing questions</h2>
    
    <div class="card" style="margin-bottom: 20px;">
      <h3>Why do plumbers charge so much?</h3>
      <p class="muted">Licensed plumbers invest in training, licensing, insurance, and specialized tools. They also handle liability for water damage if repairs fail. Hourly rates typically include overhead, not just labor.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I expect a trip charge?</h3>
      <p class="muted">Yes—most plumbers charge $50-$150 just to show up and diagnose. This is often credited toward the repair if you proceed with the work.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What's a reasonable markup on parts?</h3>
      <p class="muted">Plumbers typically mark up parts 25-50% to cover procurement, warranty handling, and inventory costs. Pricing significantly above retail is a red flag.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Can I provide my own parts?</h3>
      <p class="muted">Some plumbers allow this, but many won't warranty work done with customer-supplied parts. If you buy your own fixtures, clarify warranty terms upfront.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>When should I call a plumber vs. DIY?</h3>
      <p class="muted">Simple tasks like replacing faucet aerators or toilet flappers are DIY-friendly. Call a pro for anything involving water lines, gas lines, or work requiring permits.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What credentials should my plumber have?</h3>
      <p class="muted">Licensed, bonded, and insured is the minimum. Check their license number with your state board and verify insurance coverage before work begins.</p>
    </div>
  </div>
</section>

