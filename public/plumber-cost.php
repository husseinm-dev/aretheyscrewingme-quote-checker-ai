<section class="section">
  <div class="container narrow">
    <h2 style="text-align: center; margin-bottom: 32px;">Plumber cost breakdown by job type</h2>
    
    <div class="card" style="margin-bottom: 24px;">
      <h3>Drain cleaning & unclogging</h3>
      <p><strong>Average cost:</strong> $150–$400</p>
      <p class="muted">Simple drain snaking typically runs $150-$250, while hydro-jetting for tough clogs costs $300-$600. Camera inspections add $200-$400.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Clear explanation of method used (snake vs. hydro-jet), footage of line cleaned, and whether camera inspection is included or separate.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Leak detection & repair</h3>
      <p><strong>Average cost:</strong> $200–$500</p>
      <p class="muted">Minor leak repairs under sinks or toilets run $150-$350. Hidden leak detection with specialized equipment costs $200-$400, and wall/floor access adds labor time.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Itemized labor hours, parts breakdown (pipes, fittings, valves), and clear before/after diagnosis.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Water heater installation</h3>
      <p><strong>Average cost:</strong> $800–$2,200</p>
      <p class="muted">Tank water heater replacement costs $800-$1,500 (labor & unit), while tankless installations run $1,500-$3,500 due to electrical/gas line modifications and venting requirements.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Separate costs for unit, labor, permits, and disposal of old heater. Brand and warranty info should be clear.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Pipe repair & replacement</h3>
      <p><strong>Average cost:</strong> $250–$850</p>
      <p class="muted">Small section repairs cost $200-$400, while running new lines through walls or floors costs $500-$1,500 depending on length and accessibility.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Linear feet of pipe, type of material (PEX, copper, PVC), and whether drywall/flooring work is included.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Fixture installation (toilet, sink, faucet)</h3>
      <p><strong>Average cost:</strong> $150–$500</p>
      <p class="muted">Basic toilet or faucet installation runs $150-$300 for labor. Complex installations with new water lines or drain modifications cost $300-$600.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Labor separate from fixture cost, clear scope (is hauling away old fixture included?), and any additional parts needed.</p>
    </div>
  </div>
</section>

