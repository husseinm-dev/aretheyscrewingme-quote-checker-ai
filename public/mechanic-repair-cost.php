    <div class="card" style="margin-bottom: 20px;">
      <h3>Why do dealerships charge more than independent shops?</h3>
      <p class="muted">Dealerships have higher overhead and use only OEM parts. They offer specialized training and equipment for your make. Independent shops typically cost 20-40% less.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What's a reasonable shop supplies fee?</h3>
      <p class="muted">Most shops charge 2-10% of parts/labor for supplies (rags, cleaners, gloves). Fees over 10% or flat charges above $25 are excessive.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Should I use OEM or aftermarket parts?</h3>
      <p class="muted">For critical systems (brakes, airbags), OEM is often worth it. For wear items (filters, wipers), quality aftermarket saves money without sacrificing safety.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>How do I know if a repair is urgent?</h3>
      <p class="muted">Ask for priority level: safety-critical (brakes, steering), important but not urgent (oil leaks), or preventive (recommended but can wait).</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>Can I decline recommended services?</h3>
      <p class="muted">Absolutely. Ask for necessity vs. recommendation distinction. Get written documentation of what's declined so you have record of condition assessments.</p>
    </div>

    <div class="card" style="margin-bottom: 20px;">
      <h3>What warranty should I expect on repairs?</h3>
      <p class="muted">Reputable shops warranty labor for 12-24 months. Parts have manufacturer warranties (1-3 years typical). Get warranty terms in writing before approving work.</p>
