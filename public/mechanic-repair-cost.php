<section class="section">
  <div class="container narrow">
    <h2 style="text-align: center; margin-bottom: 32px;">Mechanic cost breakdown by repair type</h2>
    
    <div class="card" style="margin-bottom: 24px;">
      <h3>Brake service (pads & rotors)</h3>
      <p><strong>Average cost:</strong> $300–$600 per axle</p>
      <p class="muted">Front brake pads alone cost $150-$350 per axle. Adding rotor replacement brings it to $300-$600. Rear brakes typically run 10-20% less. Ceramic pads cost more but last longer.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Separate parts and labor, brand names (Wagner, Brembo, etc.), pad type (ceramic vs. semi-metallic), and rotor machining vs. replacement clearly explained.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Battery replacement</h3>
      <p><strong>Average cost:</strong> $100–$250</p>
      <p class="muted">The battery itself costs $60-$180 depending on brand and cold cranking amps. Labor adds $20-$70 for installation and disposal of old battery.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Battery brand, CCA rating, warranty length (typically 2-4 years), and installation included in price.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Alternator replacement</h3>
      <p><strong>Average cost:</strong> $400–$800</p>
      <p class="muted">Alternators cost $200-$500 for the part (new vs. rebuilt affects price). Labor runs $150-$300 (1.5-3 hours) depending on vehicle accessibility.</p>
      <p class="muted"><strong>Fair price indicators:</strong> New vs. rebuilt part specified, labor hours itemized, battery test included, and warranty on parts (1-3 years typical).</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Timing belt replacement</h3>
      <p><strong>Average cost:</strong> $500–$1,200</p>
      <p class="muted">Timing belt job requires removing engine covers and accessories—labor intensive. Most mechanics recommend replacing water pump simultaneously since labor overlaps.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Whether water pump, tensioners, and seals are included. Should specify mileage interval (typically 60K-100K miles).</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Transmission service vs. rebuild</h3>
      <p><strong>Service cost:</strong> $150–$400 | <strong>Rebuild cost:</strong> $1,500–$3,500</p>
      <p class="muted">Transmission fluid service (drain/fill) costs $150-$250. Full flush adds $50-$150. Rebuilds involve disassembly, new seals/clutches, and reassembly—major work.</p>
      <p class="muted"><strong>Fair price indicators:</strong> For rebuilds, get written warranty (12-36 months typical). Service should specify fluid type and whether filter is replaced.</p>
    </div>

    <div class="card" style="margin-bottom: 24px;">
      <h3>Diagnostic fees</h3>
      <p><strong>Average cost:</strong> $80–$150</p>
      <p class="muted">Computer diagnostics cost $80-$150. Many shops credit this toward repairs if you proceed. Check engine light diagnosis typically takes 30-60 minutes.</p>
      <p class="muted"><strong>Fair price indicators:</strong> Written diagnostic report, trouble codes explained, and fee credited toward repair if you authorize work.</p>
    </div>
  </div>
</section>

